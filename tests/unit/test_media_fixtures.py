"""The invariants of the generated media world, so nothing in 008 has to assume them.

`tests/fixtures/media.py` has no consumer yet - `media/probe.py` is T2's. That is exactly when a
fixture's invariants are worth writing down: a matrix that quietly stopped producing `hevc` would
weaken every decision test written after it and fail none of them, the failure mode
`tests/unit/test_query_fixture.py` and `tests/unit/test_image_fixture.py` were each written for one
feature earlier.

**The declaration drives the encoder and the assertions read it back through ffprobe.** Those are
two programs reading one statement from opposite ends, which is what makes "this file really is
96 kHz" a measurement instead of a comment - and it is why the numbers are never written twice
(007 T4's pattern): every assertion below compares a probed value against the matrix entry, or
compares two entries against each other, never against a literal repeated from the declaration.

Every test here carries the `ffmpeg` marker through `pytestmark`. `pytest -m "not ffmpeg"` on a
machine that has the binaries is what proves the fence is complete.
"""

