#: The entries that carry a subtitle track at all, derived rather than listed: an entry added later
#: is covered by everything below without anybody extending a tuple.
SUBTITLED: tuple[MediaFile, ...] = tuple(one for one in MATRIX if one.subtitles)


def stream_of(probed: Mapping[str, object], kind: str) -> Mapping[str, object]:
    """The one stream of a kind. Two would be a fixture nobody declared."""
    streams = [one for one in probed["streams"] if one["codec_type"] == kind]  # type: ignore[attr-defined]
    assert len(streams) == 1, f"expected exactly one {kind} stream, got {len(streams)}"
    return streams[0]


def format_of(probed: Mapping[str, object]) -> Mapping[str, object]:
    return probed["format"]  # type: ignore[return-value]


