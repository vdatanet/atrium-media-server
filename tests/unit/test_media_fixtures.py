def test_every_film_scans_to_one_item_of_the_right_type(
    scanned_media_world: ScannedMediaWorld,
) -> None:
    """One item per fixture film, and the two parts are one of them - not seven items."""
    films = scanned_media_world.by_type(ItemType.MOVIE)
    expected = {one.path for one in FILMS} - {TWO_PARTER_SECOND.path}
    assert len(films) == len(expected)

    for one in FILMS:
        item = scanned_media_world.of(one)
        assert item.type is ItemType.MOVIE, one.key
    assert (
        scanned_media_world.of(TWO_PARTER_FIRST).id == scanned_media_world.of(TWO_PARTER_SECOND).id
    ), "AC-4 of 003: a two-part film is one item, and 008 reads two sources off it"


def test_the_two_parter_carries_both_parts_in_order(
    scanned_media_world: ScannedMediaWorld,
) -> None:
    """Spec section 3.1's 'one media source per part', from the side that has to exist first."""
    item = scanned_media_world.of(TWO_PARTER_FIRST)
    assert [source.relative_path for source in item.sources] == [
        TWO_PARTER_FIRST.path,
        TWO_PARTER_SECOND.path,
    ]
    assert all(source.size and source.mtime_ns for source in item.sources)


def test_the_high_rate_track_scans_from_its_tags_and_not_its_folders(
    scanned_media_world: ScannedMediaWorld,
) -> None:
    """The file was opened, not merely listed.

    Its directories are deliberately not its album and artist, so a scan that resolved from the
    path alone would hang it under a folder name - 003 T18's failure, and the reason the delivery
    tests can trust that the row and the file describe the same thing.
    """
    track = scanned_media_world.of(HIGH_RATE_AUDIO)
    assert track.type is ItemType.AUDIO
    assert track.name == HIGH_RATE_AUDIO.tags["title"]

    albums = scanned_media_world.by_type(ItemType.MUSIC_ALBUM)
    assert [album.name for album in albums] == [HIGH_RATE_AUDIO.tags["album"]]
    artists = scanned_media_world.by_type(ItemType.MUSIC_ARTIST)
    assert [artist.name for artist in artists] == [HIGH_RATE_AUDIO.tags["album_artist"]]

    folders = {part for one in TRACKS for part in Path(one.path).parts[:-1]}
    assert folders.isdisjoint(
        {album.name for album in albums} | {artist.name for artist in artists}
    )


def test_every_scanned_source_points_at_a_file_that_exists(
    scanned_media_world: ScannedMediaWorld,
) -> None:
    """The one property this whole fixture exists to give 008, stated once.

    `tests/fixtures/query.py` cannot make this claim - it says so in its first paragraph - and a
    delivery route handed one of its identifiers would 404 at the filesystem rather than exercise
    anything.
    """
    roots = {
        scanned_media_world.movies.id: scanned_media_world.files.movies_root,
        scanned_media_world.music.id: scanned_media_world.files.music_root,
    }
    seen = 0
    for item in scanned_media_world.items.values():
        for source in item.sources:
            resolved = roots[item.library_id].joinpath(*source.relative_path.split("/"))
            assert resolved.is_file(), f"{item.name}: {resolved}"
            assert resolved.stat().st_size == source.size
            seen += 1
    assert seen == len(MATRIX)
